#!/usr/bin/env node
'use strict';

/**
 * Generate stub packages for the private `@webteam/*` dependencies.
 */

const fs = require('fs');
const path = require('path');
const { STUB_VERSION } = require('./stub-version');

const ROOT = path.resolve(__dirname, '..');
const STUBS_SCOPE_DIR = path.join(ROOT, 'webteamui-stubs', '@webteam');
const COMPONENT_SOURCE = path.join(ROOT, 'components', 'webteam-stub', 'index.js');

function fail(message) {
    console.error('ERROR: ' + message);
    process.exit(1);
}

function scanImportedNames() {
    const names = new Set();
    const hasDefault = new Set();
    const dirs = ['blocks', 'components', 'pages', 'hooks', 'utils', 'test'];
    const extensions = new Set(['.ts', '.tsx', '.js', '.jsx', '.mjs']);

    function walk(dir) {
        for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
            if (entry.name === 'node_modules' || entry.name.startsWith('.')) continue;
            const full = path.join(dir, entry.name);
            if (entry.isDirectory()) walk(full);
            else if (extensions.has(path.extname(entry.name))) {
                // Strip comments first: doc comments often contain example
                // @webteam imports that must not be collected as real names.
                const content = fs
                    .readFileSync(full, 'utf-8')
                    .replace(/\/\*[\s\S]*?\*\//g, ' ')
                    .replace(/^\s*\/\/.*$/gm, ' ');
                // [^'";] keeps the lazy clause from spanning across other import statements.
                const re = /import\s+(?:type\s+)?([^'";]*?)\s*from\s*['"](@webteam\/[^'"]+)['"]/g;
                let match;
                while ((match = re.exec(content))) {
                    const clause = match[1];
                    const braceContent = clause.match(/\{([^}]*)\}/);
                    if (braceContent) {
                        for (let item of braceContent[1].split(',')) {
                            item = item.trim();
                            if (item.startsWith('type ')) item = item.slice(5).trim();
                            const name = item.split(/\s+as\s+/)[0].trim();
                            if (name) names.add(name);
                        }
                    }
                    const bare = clause.replace(/\{[^}]*\}/g, '').replace(/,/g, '').trim();
                    if (bare) hasDefault.add(bare); // default import name
                }
            }
        }
    }

    for (const dir of dirs) {
        const full = path.join(ROOT, dir);
        if (fs.existsSync(full)) walk(full);
    }
    return { names, hasDefault };
}

function stubTypesSource({ names, hasDefault }) {
    const out = ['// AUTO-GENERATED by scripts/generate-webteam-stubs.js — do not edit.'];
    for (const name of [...names].sort()) {
        out.push(`export declare const ${name}: any;`);
        out.push(`export type ${name} = any;`);
    }
    for (const name of [...hasDefault].sort()) {
        out.push(`declare const ${name}: any;`);
        out.push(`export default ${name};`);
    }
    return out.join('\n') + '\n';
}

const STUB_CSS_NOTE = '/* AUTO-GENERATED stub stylesheet — do not edit. */';

function main() {
    const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'package.json'), 'utf-8'));
    const names = Object.keys(pkg.optionalDependencies || {}).filter((name) => name.startsWith('@webteam/'));
    if (names.length === 0) fail('No @webteam/* dependencies found in package.json.');
    if (!fs.existsSync(COMPONENT_SOURCE)) fail(`Stub component not found: ${COMPONENT_SOURCE}`);
    const componentSource = fs.readFileSync(COMPONENT_SOURCE, 'utf-8');
    const typesSource = stubTypesSource(scanImportedNames());

    fs.rmSync(STUBS_SCOPE_DIR, { recursive: true, force: true });
    for (const fullName of names) {
        const dir = path.join(STUBS_SCOPE_DIR, fullName.slice('@webteam/'.length));
        fs.mkdirSync(path.join(dir, 'lib'), { recursive: true });
        fs.mkdirSync(path.join(dir, 'css'), { recursive: true });
        fs.writeFileSync(
            path.join(dir, 'package.json'),
            JSON.stringify(
                { name: fullName, version: STUB_VERSION, private: true, main: 'lib/index.js', types: 'lib/index.d.ts', license: 'Apache-2.0' },
                null,
                4
            ) + '\n'
        );
        fs.writeFileSync(path.join(dir, 'lib', 'index.js'), componentSource);
        fs.writeFileSync(path.join(dir, 'lib', 'index.d.ts'), typesSource);
        fs.writeFileSync(path.join(dir, 'lib', 'index.css'), STUB_CSS_NOTE);
        fs.writeFileSync(path.join(dir, 'css', 'offset.css'), STUB_CSS_NOTE);
    }
    console.log(`Generated ${names.length} stub packages in webteamui-stubs/@webteam/, all pointing at components/webteam-stub.`);
}

main();
